#!/usr/bin/env node
/**
 * Generate maze constants for all codebases from single source of truth.
 *
 * Reads maze-config.json and generates:
 * - TypeScript: frontend/src/lib/mazeConstants.generated.ts
 * - Solidity: contracts/src/MazeConstants.sol
 * - Noir constants block (for manual paste or verification)
 *
 * Usage: node scripts/generate-maze-constants.js
 */

const fs = require('fs');
const path = require('path');

const PROJECT_ROOT = path.join(__dirname, '..');
const CONFIG_FILE = path.join(PROJECT_ROOT, 'maze-config.json');

// Output paths
const TS_OUTPUT = path.join(PROJECT_ROOT, 'frontend/src/lib/mazeConstants.generated.ts');
const SOL_OUTPUT = path.join(PROJECT_ROOT, 'contracts/src/MazeConstants.sol');
const NOIR_MAIN = path.join(PROJECT_ROOT, 'maze_prover/src/main.nr');

// Colors for terminal
const C = {
  RED: '\x1b[0;31m',
  GREEN: '\x1b[0;32m',
  YELLOW: '\x1b[1;33m',
  BLUE: '\x1b[0;34m',
  NC: '\x1b[0m',
};

function log(color, tag, msg) {
  console.log(`${color}[${tag}]${C.NC} ${msg}`);
}

function error(msg) {
  log(C.RED, 'constants', `Error: ${msg}`);
  process.exit(1);
}

function loadConfig() {
  if (!fs.existsSync(CONFIG_FILE)) {
    error(`Config file not found: ${CONFIG_FILE}`);
  }

  const raw = fs.readFileSync(CONFIG_FILE, 'utf8');
  const config = JSON.parse(raw);

  // Extract base values
  const maxMazeCells = config.maxMazeCells;
  const maxMoves = config.maxMoves;

  // Compute derived values
  const maxPackedBytes = Math.floor(maxMazeCells / 2);
  // Public inputs: width, height, start_x, start_y, key_x, key_y, goal_x, goal_y (8)
  //                + packed_cells (maxPackedBytes) + move_count (1)
  const publicInputsLength = 8 + maxPackedBytes + 1;
  // Maze data for tokenId hash: all public inputs except move_count
  const mazeDataLength = 8 + maxPackedBytes;

  return {
    maxMazeCells,
    maxMoves,
    maxPackedBytes,
    publicInputsLength,
    mazeDataLength,
  };
}

function generateTypeScript(config) {
  const timestamp = new Date().toISOString();

  return `/**
 * Auto-generated maze constants
 * Generated at: ${timestamp}
 * Source: maze-config.json
 *
 * DO NOT EDIT THIS FILE MANUALLY
 * Regenerate with: just generate-constants
 */

/** Maximum total cells in a maze (width * height) */
export const MAX_MAZE_CELLS = ${config.maxMazeCells};

/** Maximum packed bytes for cell data (2 cells per byte) */
export const MAX_PACKED_BYTES = ${config.maxPackedBytes};

/** Maximum number of moves in a solution */
export const MAX_MOVES = ${config.maxMoves};

/**
 * Number of public inputs for ZK proof verification.
 * = 8 scalar params + MAX_PACKED_BYTES + 1 move_count
 */
export const PUBLIC_INPUTS_LENGTH = ${config.publicInputsLength};

/**
 * Number of elements used for maze identity hash (tokenId calculation).
 * = PUBLIC_INPUTS_LENGTH - 1 (excludes move_count)
 */
export const MAZE_DATA_LENGTH = ${config.mazeDataLength};
`;
}

function generateSolidity(config) {
  const timestamp = new Date().toISOString();

  return `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

/**
 * @title MazeConstants
 * @notice Auto-generated maze constants from maze-config.json
 * @dev Generated at: ${timestamp}
 *      DO NOT EDIT THIS FILE MANUALLY
 *      Regenerate with: just generate-constants
 */
library MazeConstants {
    /// @notice Maximum total cells in a maze (width * height)
    uint256 internal constant MAX_MAZE_CELLS = ${config.maxMazeCells};

    /// @notice Maximum packed bytes for cell data (2 cells per byte)
    uint256 internal constant MAX_PACKED_BYTES = ${config.maxPackedBytes};

    /// @notice Maximum number of moves in a solution
    uint256 internal constant MAX_MOVES = ${config.maxMoves};

    /**
     * @notice Number of public inputs for ZK proof verification
     * @dev = 8 scalar params + MAX_PACKED_BYTES + 1 move_count
     */
    uint256 internal constant PUBLIC_INPUTS_LENGTH = ${config.publicInputsLength};

    /**
     * @notice Number of elements used for maze identity hash (tokenId)
     * @dev = PUBLIC_INPUTS_LENGTH - 1 (excludes move_count)
     */
    uint256 internal constant MAZE_DATA_LENGTH = ${config.mazeDataLength};
}
`;
}

function generateNoirConstants(config) {
  return `// === AUTO-GENERATED CONSTANTS ===
// Source: maze-config.json
// Regenerate with: just generate-constants
// DO NOT EDIT BETWEEN MARKERS

// Maximum cells supported
global MAX_MAZE_CELLS: u32 = ${config.maxMazeCells};
// Maximum packed bytes (2 cells per byte)
global MAX_PACKED_BYTES: u32 = MAX_MAZE_CELLS / 2;
// Maximum moves supported
global MAX_MOVES: u32 = ${config.maxMoves};

// === END AUTO-GENERATED CONSTANTS ===`;
}

function updateNoirMain(config) {
  if (!fs.existsSync(NOIR_MAIN)) {
    log(C.YELLOW, 'noir', 'main.nr not found, skipping Noir update');
    return false;
  }

  let content = fs.readFileSync(NOIR_MAIN, 'utf8');

  // Check if constants match
  const maxCellsMatch = content.match(/global MAX_MAZE_CELLS: u32 = (\d+);/);
  const maxMovesMatch = content.match(/global MAX_MOVES: u32 = (\d+);/);

  if (maxCellsMatch && maxMovesMatch) {
    const currentMaxCells = parseInt(maxCellsMatch[1], 10);
    const currentMaxMoves = parseInt(maxMovesMatch[1], 10);

    if (currentMaxCells === config.maxMazeCells && currentMaxMoves === config.maxMoves) {
      log(C.GREEN, 'noir', 'Constants already match, no update needed');
      return true;
    }

    // Update the values
    content = content.replace(
      /global MAX_MAZE_CELLS: u32 = \d+;/,
      `global MAX_MAZE_CELLS: u32 = ${config.maxMazeCells};`
    );
    content = content.replace(
      /global MAX_MOVES: u32 = \d+;/,
      `global MAX_MOVES: u32 = ${config.maxMoves};`
    );

    fs.writeFileSync(NOIR_MAIN, content, 'utf8');
    log(C.GREEN, 'noir', `Updated main.nr: MAX_MAZE_CELLS=${config.maxMazeCells}, MAX_MOVES=${config.maxMoves}`);
    return true;
  }

  log(C.YELLOW, 'noir', 'Could not find constants pattern in main.nr');
  return false;
}

function main() {
  log(C.BLUE, 'constants', 'Generating maze constants from maze-config.json...');

  const config = loadConfig();

  log(C.YELLOW, 'constants', 'Configuration:');
  console.log(`  MAX_MAZE_CELLS:      ${config.maxMazeCells}`);
  console.log(`  MAX_PACKED_BYTES:    ${config.maxPackedBytes}`);
  console.log(`  MAX_MOVES:           ${config.maxMoves}`);
  console.log(`  PUBLIC_INPUTS_LENGTH: ${config.publicInputsLength}`);
  console.log(`  MAZE_DATA_LENGTH:    ${config.mazeDataLength}`);
  console.log('');

  // Generate TypeScript
  const tsContent = generateTypeScript(config);
  fs.mkdirSync(path.dirname(TS_OUTPUT), { recursive: true });
  fs.writeFileSync(TS_OUTPUT, tsContent, 'utf8');
  log(C.GREEN, 'typescript', `Generated ${TS_OUTPUT}`);

  // Generate Solidity
  const solContent = generateSolidity(config);
  fs.mkdirSync(path.dirname(SOL_OUTPUT), { recursive: true });
  fs.writeFileSync(SOL_OUTPUT, solContent, 'utf8');
  log(C.GREEN, 'solidity', `Generated ${SOL_OUTPUT}`);

  // Update Noir
  updateNoirMain(config);

  // Print Noir constants for reference
  console.log('');
  log(C.BLUE, 'noir', 'Noir constants (for reference):');
  console.log(generateNoirConstants(config));
  console.log('');

  log(C.GREEN, 'constants', 'Generation complete!');
}

try {
  main();
} catch (err) {
  error(err.message);
}
