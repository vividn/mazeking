#!/usr/bin/env node
/**
 * Generate TypeScript contracts configuration for frontend
 * Reads deployment JSON and contract ABIs, outputs typed TypeScript file
 *
 * Usage: node generate-contracts-config.js <chainId>
 * Example: node generate-contracts-config.js 31337
 */

const fs = require('fs');
const path = require('path');

const PROJECT_ROOT = path.join(__dirname, '..');
const CONTRACTS_DIR = path.join(PROJECT_ROOT, 'contracts');
const DEPLOYMENTS_DIR = path.join(CONTRACTS_DIR, 'deployments');
const CONTRACTS_OUT_DIR = path.join(CONTRACTS_DIR, 'out');
const FRONTEND_DIR = path.join(PROJECT_ROOT, 'frontend');
const OUTPUT_FILE = path.join(FRONTEND_DIR, 'src', 'lib', 'contracts.generated.ts');
const ABI_DIR = path.join(FRONTEND_DIR, 'src', 'lib', 'abi');

// Color codes for terminal output
const COLORS = {
  RED: '\x1b[0;31m',
  GREEN: '\x1b[0;32m',
  YELLOW: '\x1b[1;33m',
  BLUE: '\x1b[0;34m',
  NC: '\x1b[0m',
};

function log(color, tag, message) {
  console.log(`${color}[${tag}]${COLORS.NC} ${message}`);
}

function error(message) {
  log(COLORS.RED, 'config-gen', `Error: ${message}`);
  process.exit(1);
}

function main() {
  const chainId = process.argv[2];

  if (!chainId) {
    error('Chain ID not provided. Usage: node generate-contracts-config.js <chainId>');
  }

  log(COLORS.BLUE, 'config-gen', `Generating contracts config for chain ${chainId}...`);

  // Read deployment JSON
  const deploymentFile = path.join(DEPLOYMENTS_DIR, `${chainId}.json`);
  if (!fs.existsSync(deploymentFile)) {
    error(`Deployment file not found: ${deploymentFile}`);
  }

  log(COLORS.YELLOW, 'config-gen', `Reading deployment from ${deploymentFile}`);
  const deployment = JSON.parse(fs.readFileSync(deploymentFile, 'utf8'));

  // Extract ABIs from forge output
  log(COLORS.YELLOW, 'config-gen', 'Extracting ABIs from forge output...');

  const nftForgeOutput = path.join(CONTRACTS_OUT_DIR, 'MazeKingNFT.sol', 'MazeKingNFT.json');
  const verifierForgeOutput = path.join(CONTRACTS_OUT_DIR, 'MazeVerifier.sol', 'HonkVerifier.json');

  if (!fs.existsSync(nftForgeOutput)) {
    error(`NFT contract output not found: ${nftForgeOutput}. Run 'forge build' first.`);
  }

  if (!fs.existsSync(verifierForgeOutput)) {
    error(`Verifier contract output not found: ${verifierForgeOutput}. Run 'forge build' first.`);
  }

  const nftForge = JSON.parse(fs.readFileSync(nftForgeOutput, 'utf8'));
  const verifierForge = JSON.parse(fs.readFileSync(verifierForgeOutput, 'utf8'));

  const nftAbi = nftForge.abi;
  const verifierAbi = verifierForge.abi;

  // Also save ABIs to frontend abi directory for backward compatibility
  log(COLORS.YELLOW, 'config-gen', 'Saving ABIs to frontend/src/lib/abi/...');
  fs.mkdirSync(ABI_DIR, { recursive: true });
  fs.writeFileSync(path.join(ABI_DIR, 'MazeKingNFT.json'), JSON.stringify(nftAbi, null, 2));
  fs.writeFileSync(path.join(ABI_DIR, 'MazeVerifier.json'), JSON.stringify(verifierAbi, null, 2));

  // Generate TypeScript file
  const timestamp = new Date().toISOString();
  const content = `/**
 * Auto-generated contract configuration
 * Generated at: ${timestamp}
 * Chain ID: ${chainId}
 *
 * DO NOT EDIT THIS FILE MANUALLY
 * Regenerate with: just deploy-local or just deploy-sepolia
 */

export const CONTRACT_ADDRESSES = {
  ${chainId}: {
    nft: '${deployment.nft}' as const,
    verifier: '${deployment.verifier}' as const,
  },
} as const;

export const CONTRACT_ABIS = {
  nft: ${JSON.stringify(nftAbi, null, 2)} as const,
  verifier: ${JSON.stringify(verifierAbi, null, 2)} as const,
} as const;

export type SupportedChainId = keyof typeof CONTRACT_ADDRESSES;
export type ContractType = keyof typeof CONTRACT_ADDRESSES[SupportedChainId];

/**
 * Get contract address for a given chain and contract type
 */
export function getContractAddress(
  chainId: number,
  contract: ContractType
): \`0x\${string}\` | undefined {
  const addresses = CONTRACT_ADDRESSES[chainId as SupportedChainId];
  return addresses?.[contract];
}

/**
 * Get contract ABI
 */
export function getContractAbi(contract: ContractType) {
  return CONTRACT_ABIS[contract];
}

/**
 * Check if contracts are deployed on a given chain
 */
export function areContractsDeployed(chainId: number): boolean {
  const nft = getContractAddress(chainId, 'nft');
  const verifier = getContractAddress(chainId, 'verifier');
  return !!nft && !!verifier;
}

/**
 * Deployment metadata
 */
export const DEPLOYMENT_INFO = {
  chainId: ${deployment.chainId},
  deployer: '${deployment.deployer}' as const,
  timestamp: ${deployment.timestamp},
  deployedAt: new Date(${deployment.timestamp} * 1000).toISOString(),
} as const;
`;

  // Write output file
  fs.writeFileSync(OUTPUT_FILE, content, 'utf8');
  log(COLORS.GREEN, 'config-gen', `Generated ${OUTPUT_FILE}`);

  // Update main contracts.ts to use generated file
  const contractsFile = path.join(FRONTEND_DIR, 'src', 'lib', 'contracts.ts');
  const contractsContent = `/**
 * Contract configuration
 *
 * This file imports the auto-generated configuration.
 * To regenerate: just deploy-local or just deploy-sepolia
 */

export * from './contracts.generated';
`;

  fs.writeFileSync(contractsFile, contractsContent, 'utf8');
  log(COLORS.GREEN, 'config-gen', 'Updated contracts.ts');

  log(COLORS.GREEN, 'config-gen', 'Configuration generation complete!');
  console.log('');
  console.log(`  NFT Address:      ${deployment.nft}`);
  console.log(`  Verifier Address: ${deployment.verifier}`);
  console.log(`  Chain ID:         ${deployment.chainId}`);
}

try {
  main();
} catch (err) {
  error(err.message);
}
