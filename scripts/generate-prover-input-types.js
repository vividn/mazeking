#!/usr/bin/env node
/**
 * Codegen the ProverInput TypeScript interface from the circuit's compiled
 * ABI. Sibling gate to scripts/check-abi-drift.js (ma-3xv): that script
 * validates *count* of public inputs and presence of named fields; this one
 * validates the *field shape* of `generateProverInput`'s return type so that
 * any drift surfaces as a TypeScript error rather than nargo's runtime
 * "input not found" (see retro Appendix C; bead ma-7qm).
 *
 * Source of truth:
 *   maze_prover/target/maze_prover.json  (Noir-emitted ABI)
 *
 * Output:
 *   frontend/src/lib/proverInput.generated.ts
 *     - interface ProverInputCircuit  (exact key set keyed by ABI param name)
 *     - const PROVER_INPUT_KEYS       (runtime-iterable list, same order)
 *     - const PROVER_PUBLIC_INPUT_KEYS (the `pub` subset)
 *
 * `zkSerialize.ts` aliases `ProverInput = ProverInputCircuit`; TS excess /
 * missing-property checking on the object literal returned by
 * `generateProverInput` then enforces drift detection at compile time.
 *
 * Idempotent: re-running with an unchanged ABI produces a byte-identical
 * output file. Wired into CI via `just verify-prover-input-types`.
 */

const fs = require('fs');
const path = require('path');

const PROJECT_ROOT = path.join(__dirname, '..');
const CIRCUIT_ABI = path.join(
  PROJECT_ROOT,
  'maze_prover/target/maze_prover.json'
);
const OUTPUT_FILE = path.join(
  PROJECT_ROOT,
  'frontend/src/lib/proverInput.generated.ts'
);

const C = {
  RED: '\x1b[0;31m',
  GREEN: '\x1b[0;32m',
  YELLOW: '\x1b[1;33m',
  BLUE: '\x1b[0;34m',
  NC: '\x1b[0m',
};

function log(color, tag, msg) {
  console.log(`${color}[${tag}]${C.NC} ${msg}`);
}

function fail(msg) {
  console.error(`${C.RED}[prover-input-types]${C.NC} ${msg}`);
  process.exit(1);
}

function loadAbi() {
  if (!fs.existsSync(CIRCUIT_ABI)) {
    fail(
      `Circuit artifact not found: ${CIRCUIT_ABI}. ` +
        `Run \`just compile-circuits\` first.`
    );
  }
  let parsed;
  try {
    parsed = JSON.parse(fs.readFileSync(CIRCUIT_ABI, 'utf8'));
  } catch (e) {
    fail(`Failed to parse circuit JSON: ${e.message}`);
  }
  if (!parsed.abi || !Array.isArray(parsed.abi.parameters)) {
    fail(`Circuit JSON missing .abi.parameters array`);
  }
  return parsed.abi.parameters;
}

// Convert a Noir ABI type to a TypeScript type expression and a human-readable
// comment describing the original ABI shape. Throws on unknown kinds so that
// future ABI extensions are caught loudly rather than silently mistyped.
function abiTypeToTs(abiType) {
  switch (abiType.kind) {
    case 'field':
      // Field elements are 32-byte BN254 scalars; we serialize as 0x-prefixed
      // hex (matches viem's bytes32). The circuit accepts decimal too, but
      // hex is the convention this codebase uses (see frToBytes32.ts).
      return { ts: '`0x${string}`', comment: 'Field (32-byte BN254 scalar)' };
    case 'integer': {
      if (abiType.sign !== 'unsigned') {
        fail(`Unsupported signed integer in ABI: ${JSON.stringify(abiType)}`);
      }
      if (abiType.width > 53) {
        fail(
          `Integer width ${abiType.width} exceeds JS Number safe range; ` +
            `would need bigint codegen support`
        );
      }
      return { ts: 'number', comment: `u${abiType.width}` };
    }
    case 'array': {
      const inner = abiTypeToTs(abiType.type);
      return {
        ts: `${inner.ts}[]`,
        comment: `[${inner.comment}; ${abiType.length}]`,
      };
    }
    default:
      fail(`Unknown ABI type kind "${abiType.kind}": ${JSON.stringify(abiType)}`);
      return null; // unreachable
  }
}

function renderInterface(params) {
  const lines = [];
  for (const p of params) {
    const ty = abiTypeToTs(p.type);
    const visibility = p.visibility === 'public' ? 'public' : 'private';
    lines.push(`  /** ${visibility} · ${ty.comment} */`);
    lines.push(`  ${p.name}: ${ty.ts};`);
  }
  return lines.join('\n');
}

function renderKeysArray(params) {
  return params.map((p) => `  '${p.name}',`).join('\n');
}

function generateOutput(params) {
  const publicNames = params
    .filter((p) => p.visibility === 'public')
    .map((p) => p.name);

  return `/**
 * Auto-generated from maze_prover/target/maze_prover.json
 *
 * DO NOT EDIT THIS FILE MANUALLY.
 * Regenerate with: just generate-prover-input-types
 *
 * This file is the source of truth for the TypeScript shape of the prover
 * input. \`zkSerialize.ts\` aliases \`ProverInput = ProverInputCircuit\`, so
 * any drift between the Noir circuit's main() signature and the object
 * returned by \`generateProverInput\` is caught at TypeScript compile time
 * (rather than at proof time, where nargo's "input not found" error is
 * cryptic — see retro Appendix C, bead ma-7qm).
 *
 * Sibling to \`scripts/check-abi-drift.js\` (ma-3xv): that gate validates the
 * *count* of \`pub\` params; this one pins the *field shape*.
 */

/* eslint-disable */

/**
 * Prover input shape, generated from the circuit ABI.
 *
 * Field order matches the circuit's main() parameter list. Noir's InputMap
 * is name-keyed at the witness layer, so the order in this object is
 * irrelevant to proof validity — but matching it keeps diffs minimal when
 * the circuit is extended.
 */
export interface ProverInputCircuit {
${renderInterface(params)}
}

/**
 * Runtime-iterable list of every key in {@link ProverInputCircuit}, in
 * circuit ABI declaration order. Useful for asserting at runtime that an
 * input object has every required field populated (e.g. tests, debug logs).
 */
export const PROVER_INPUT_KEYS = [
${renderKeysArray(params)}
] as const satisfies ReadonlyArray<keyof ProverInputCircuit>;

/**
 * Subset of {@link PROVER_INPUT_KEYS} marked \`pub\` in the circuit (i.e.
 * exposed on-chain via the verifier). Keep aligned with
 * \`MazeConstants.PUBLIC_INPUTS_LENGTH\` — \`scripts/check-abi-drift.js\`
 * enforces that count.
 */
export const PROVER_PUBLIC_INPUT_KEYS = [
${publicNames.map((n) => `  '${n}',`).join('\n')}
] as const satisfies ReadonlyArray<keyof ProverInputCircuit>;
`;
}

function main() {
  log(C.BLUE, 'prover-input-types', `Reading ABI from ${CIRCUIT_ABI}`);
  const params = loadAbi();
  log(
    C.YELLOW,
    'prover-input-types',
    `Parsed ${params.length} params (${params.filter((p) => p.visibility === 'public').length} public)`
  );

  const output = generateOutput(params);

  fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
  fs.writeFileSync(OUTPUT_FILE, output, 'utf8');
  log(C.GREEN, 'prover-input-types', `Wrote ${OUTPUT_FILE}`);
}

main();
