#!/usr/bin/env node
/**
 * Regenerate cross-layer Pedersen fixtures (ma-bu3 / pawn retro Appendix C).
 *
 * Single source of truth: `maze_prover/test_data/layout_fixtures.json`.
 *
 * Pipeline:
 *   1. Read fixture spec JSON (header u16s + sparse packed_cells overrides).
 *   2. Codegen `maze_prover/src/fixtures_codegen.nr` — a Noir test that
 *      constructs each fixture's layout, calls `compute_maze_hash`, and
 *      prints `FIXTURE_HASH:<name>=0x<64hex>` to stdout.
 *   3. Run `nargo test test_emit_pedersen_fixtures --show-output` and parse
 *      the printed hashes.
 *   4. Write `frontend/src/lib/__tests__/pedersen_fixtures.json` with the
 *      same fixture entries plus the Noir-computed `expectedHash`.
 *
 * Idempotent: the Pedersen hash is deterministic, so re-running with an
 * unchanged source JSON produces a byte-identical output JSON. Drift between
 * TS and Noir byte-encoding immediately fails the vitest in
 * `frontend/src/lib/__tests__/pedersenFixtures.test.ts`.
 *
 * Usage:
 *   node scripts/regen-pedersen-fixtures.js
 *   just regen-pedersen-fixtures
 */

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const PROJECT_ROOT = path.join(__dirname, '..');
const SOURCE_JSON = path.join(
  PROJECT_ROOT,
  'maze_prover/test_data/layout_fixtures.json'
);
const NOIR_OUTPUT = path.join(
  PROJECT_ROOT,
  'maze_prover/src/fixtures_codegen.nr'
);
const FRONTEND_OUTPUT = path.join(
  PROJECT_ROOT,
  'frontend/src/lib/__tests__/pedersen_fixtures.json'
);
const NARGO = process.env.NARGO_PATH || 'nargo';

const C = {
  RED: '\x1b[0;31m',
  GREEN: '\x1b[0;32m',
  YELLOW: '\x1b[1;33m',
  BLUE: '\x1b[0;34m',
  NC: '\x1b[0m',
};

function log(color, tag, msg) {
  console.log(`${color}[${tag}]${C.NC} ${msg}`);
}

function fail(msg) {
  log(C.RED, 'pedersen-fixtures', `Error: ${msg}`);
  process.exit(1);
}

function loadSource() {
  if (!fs.existsSync(SOURCE_JSON)) {
    fail(`Source fixtures not found: ${SOURCE_JSON}`);
  }
  const raw = JSON.parse(fs.readFileSync(SOURCE_JSON, 'utf8'));
  if (!Array.isArray(raw.fixtures) || raw.fixtures.length === 0) {
    fail(`Source must contain a non-empty "fixtures" array`);
  }
  for (const fx of raw.fixtures) {
    validateFixture(fx);
  }
  const seen = new Set();
  for (const fx of raw.fixtures) {
    if (seen.has(fx.name)) {
      fail(`Duplicate fixture name: ${fx.name}`);
    }
    seen.add(fx.name);
  }
  return raw.fixtures;
}

function validateFixture(fx) {
  if (typeof fx.name !== 'string' || !/^[a-zA-Z0-9._-]+$/.test(fx.name)) {
    fail(
      `Bad fixture name (must be [a-zA-Z0-9._-]+): ${JSON.stringify(fx.name)}`
    );
  }
  if (
    !Array.isArray(fx.header) ||
    fx.header.length !== 10 ||
    !fx.header.every((n) => Number.isInteger(n) && n >= 0 && n <= 0xffff)
  ) {
    fail(`Fixture "${fx.name}": header must be 10 u16 ints in [0, 65535]`);
  }
  if (
    !Number.isInteger(fx.packedFill) ||
    fx.packedFill < 0 ||
    fx.packedFill > 0xff
  ) {
    fail(`Fixture "${fx.name}": packedFill must be a u8 in [0, 255]`);
  }
  if (fx.packedOverrides !== undefined) {
    if (!Array.isArray(fx.packedOverrides)) {
      fail(`Fixture "${fx.name}": packedOverrides must be an array`);
    }
    for (const ov of fx.packedOverrides) {
      if (
        !Array.isArray(ov) ||
        ov.length !== 2 ||
        !Number.isInteger(ov[0]) ||
        ov[0] < 0 ||
        ov[0] >= 1500 ||
        !Number.isInteger(ov[1]) ||
        ov[1] < 0 ||
        ov[1] > 0xff
      ) {
        fail(
          `Fixture "${fx.name}": packedOverrides entry must be [u32 in [0,1500), u8 in [0,255]] — got ${JSON.stringify(ov)}`
        );
      }
    }
  }
}

function generateNoirSource(fixtures) {
  const lines = [];
  lines.push(
    '// AUTO-GENERATED by scripts/regen-pedersen-fixtures.js -- do not edit.'
  );
  lines.push('// Source: maze_prover/test_data/layout_fixtures.json');
  lines.push('//');
  lines.push(
    '// Emits one `FIXTURE_HASH:<name>=0x<hex>` line per fixture so the'
  );
  lines.push(
    '// recipe can capture Noir-side hashes and write the cross-layer'
  );
  lines.push('// `pedersen_fixtures.json` consumed by vitest.');
  lines.push('');
  lines.push('use crate::hash::{MAX_PACKED_BYTES, compute_maze_hash};');
  lines.push('');
  lines.push('#[test]');
  lines.push('fn test_emit_pedersen_fixtures() {');
  for (const fx of fixtures) {
    const [w, h, sx, sy, rx, ry, scx, scy, gx, gy] = fx.header;
    lines.push(`    // -- fixture: ${fx.name} --`);
    lines.push('    {');
    lines.push(
      `        let mut packed: [u8; MAX_PACKED_BYTES] = [${fx.packedFill}; MAX_PACKED_BYTES];`
    );
    for (const [idx, byte] of fx.packedOverrides ?? []) {
      lines.push(`        packed[${idx}] = ${byte};`);
    }
    lines.push(
      `        let h = compute_maze_hash(${w}, ${h}, ${sx}, ${sy}, ${rx}, ${ry}, ${scx}, ${scy}, ${gx}, ${gy}, packed);`
    );
    lines.push(`        println(f"FIXTURE_HASH:${fx.name}={h}");`);
    lines.push('    }');
  }
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

function writeFileIfChanged(filePath, content) {
  const existed = fs.existsSync(filePath);
  const prev = existed ? fs.readFileSync(filePath, 'utf8') : null;
  if (prev === content) {
    log(C.YELLOW, 'pedersen-fixtures', `Unchanged: ${path.relative(PROJECT_ROOT, filePath)}`);
    return false;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content);
  log(
    C.GREEN,
    'pedersen-fixtures',
    `${existed ? 'Updated' : 'Wrote'}: ${path.relative(PROJECT_ROOT, filePath)}`
  );
  return true;
}

function runNargo() {
  const cwd = path.join(PROJECT_ROOT, 'maze_prover');
  log(C.BLUE, 'pedersen-fixtures', `Running ${NARGO} test test_emit_pedersen_fixtures --show-output`);
  const result = spawnSync(
    NARGO,
    ['test', 'test_emit_pedersen_fixtures', '--show-output'],
    { cwd, encoding: 'utf8' }
  );
  if (result.error) {
    fail(`Failed to spawn nargo: ${result.error.message}`);
  }
  if (result.status !== 0) {
    process.stderr.write(result.stdout || '');
    process.stderr.write(result.stderr || '');
    fail(`nargo test exited with status ${result.status}`);
  }
  return (result.stdout || '') + (result.stderr || '');
}

function parseHashes(stdout, expectedNames) {
  const re = /FIXTURE_HASH:([^=\s]+)=(0x[0-9a-fA-F]+)/g;
  const found = new Map();
  let match;
  while ((match = re.exec(stdout))) {
    const [, name, hex] = match;
    found.set(name, hex.toLowerCase());
  }
  for (const name of expectedNames) {
    if (!found.has(name)) {
      fail(`nargo stdout did not emit FIXTURE_HASH for "${name}"`);
    }
    const hex = found.get(name);
    if (!/^0x[0-9a-f]{1,64}$/.test(hex)) {
      fail(`Invalid hash hex for "${name}": ${hex}`);
    }
  }
  // Normalize to 0x + 64 hex chars (Field elements may print with leading
  // zeros stripped; left-pad to 32 bytes for stable cross-layer comparison).
  const normalized = new Map();
  for (const [name, hex] of found) {
    const stripped = hex.slice(2);
    normalized.set(name, '0x' + stripped.padStart(64, '0'));
  }
  return normalized;
}

function buildOutput(fixtures, hashes) {
  const out = {
    _doc: [
      'AUTO-GENERATED by scripts/regen-pedersen-fixtures.js — do not edit.',
      'Source: maze_prover/test_data/layout_fixtures.json',
      'Each entry pins a Noir-computed `expectedHash` against the canonical',
      '1520-byte layout reconstructed from header + packedFill + packedOverrides.',
      'The vitest in `pedersenFixtures.test.ts` reconstructs the layout, calls',
      '`computeMazeHash`, and asserts byte-identical equality with `expectedHash`.',
    ],
    fixtures: fixtures.map((fx) => ({
      name: fx.name,
      description: fx.description ?? '',
      header: fx.header,
      packedFill: fx.packedFill,
      ...(fx.packedOverrides ? { packedOverrides: fx.packedOverrides } : {}),
      expectedHash: hashes.get(fx.name),
    })),
  };
  return JSON.stringify(out, null, 2) + '\n';
}

function main() {
  log(
    C.BLUE,
    'pedersen-fixtures',
    `Regenerating Pedersen fixtures from ${path.relative(PROJECT_ROOT, SOURCE_JSON)}`
  );
  const fixtures = loadSource();
  log(
    C.YELLOW,
    'pedersen-fixtures',
    `${fixtures.length} fixture(s): ${fixtures.map((f) => f.name).join(', ')}`
  );

  const noirSrc = generateNoirSource(fixtures);
  writeFileIfChanged(NOIR_OUTPUT, noirSrc);

  const stdout = runNargo();
  const hashes = parseHashes(
    stdout,
    fixtures.map((f) => f.name)
  );

  const outJson = buildOutput(fixtures, hashes);
  writeFileIfChanged(FRONTEND_OUTPUT, outJson);

  log(C.GREEN, 'pedersen-fixtures', 'Done.');
}

main();
